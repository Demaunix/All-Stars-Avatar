"""Per-slot item list of the Xbox 360 Avatar Asset Package (M10 phase 1, step 2). Read-only.

Writes research/catalog-slots.tsv (one row per TOC record that has a payload) and research/catalog-slots.md (grouped by slot).
Columns: index, slot (primary), bits (every slot bit of the record), gender (TOC variant top byte: 1 male, 2 female, 3 both;
byte 2 is 0 for some items such as Male Suit and Tie 0x1000000, so it is kept separately as vbyte2), kind, name, alt names,
decoded bytes, hiding template index (garments), "(Hat)" partner index (hair, matched by name), texture frames (spans).

Slot bits are TOC word 0 (research/AVATAR-MODEL-FORMAT.md). A multi-slot item (top+wrist 0x208, gloves+ring 0x880,
costume 0x800xxx) is listed once under its primary slot with all bits shown.
"""
import sys
from collections import OrderedDict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import avatar_hiding as H
import avatar_texture as AT
from catalog import MODULE, catalog, decoded

# "(Hat)" hair variants whose hat-less partner has a different name. Paired by index adjacency (the pack lists each hat
# variant right after its base style) and by sense. 453 "Parting (Hat)" goes with 451 "Right Parting" only: 452 "Left
# Parting" already has 961 "Left Parting (Hat)" by name (independent check 2026-10-21). 444 "Right Comb Over" has no hat
# variant at all. Not verified against console behaviour.
HAT_PARTNER_OVERRIDES = {439: "438", 453: "451", 479: "478", 533: "532", 562: "561", 564: "563", 594: "593"}
SLOTS = OrderedDict([(0x1, "head"), (0x2, "body"), (0x4, "hair"), (0x8, "top"), (0x10, "bottom"), (0x20, "shoes"), (0x40, "hat"),
                     (0x80, "gloves"), (0x100, "glasses"), (0x200, "wrist"), (0x400, "earrings"), (0x800, "ring"), (0x2000, "eyes"),
                     (0x4000, "eyebrows"), (0x8000, "mouth"), (0x10000, "facial hair"), (0x20000, "face paint"), (0x40000, "eye shadow"),
                     (0x80000, "nose"), (0x100000, "chin"), (0x200000, "ears"), (0x400000, "animation"), (0x800000, "costume"),
                     (0x1000000, "hiding template")])
GENDER = {1: "male", 2: "female", 3: "both"}


def bits_of(t: int) -> list:
    """Slot names of every bit set in a TOC type word (unknown bits as hex)."""
    out = [n for b, n in SLOTS.items() if t & b]
    rest = t & ~sum(SLOTS)
    if rest:
        out.append(hex(rest))
    return out


def primary(t: int) -> str:
    """Primary slot: costume if that bit is set, else the lowest set bit."""
    if t & 0x800000:
        return "costume"
    for b, n in SLOTS.items():
        if t & b:
            return n
    return hex(t)


def main() -> None:
    """Build both listings from the pinned catalogue."""
    rows = catalog()
    by_name = {}
    for c in rows:
        by_name.setdefault((c["name"], c["type"]), []).append(c)
    out = []
    for c in rows:
        t, g = c["type"], (c["variant"] >> 24) & 0xFF
        tpl = ""
        if c["kind"] == "model" and t != 0x1000000:
            try:
                tpl = H.template_for(c["index"])
                tpl = "" if tpl is None else str(tpl)
            except H.HidingError as e:
                tpl = f"ERR {e}"
        partner = ""
        if t == 0x4 and c["name"].endswith(" (Hat)"):
            base = by_name.get((c["name"][:-6], t), [])
            partner = ",".join(str(b["index"]) for b in base) if base else HAT_PARTNER_OVERRIDES.get(c["index"], "NONE")
            if c["index"] in HAT_PARTNER_OVERRIDES:
                partner += " (by adjacency)"
        frames = ""
        if c["kind"] == "texture":
            try:
                frames = str(AT.standalone(decoded(c["index"]))["spans"])
            except AT.TextureError as e:
                frames = f"ERR {e}"
        empty = c["decoded_bytes"] is not None and c["decoded_bytes"] < 0x58 and c["kind"] == "model"
        alt = [n for n in c["names"][1:] if n.strip() and n != c["name"]]
        out.append(dict(index=c["index"], slot=primary(t), bits="+".join(bits_of(t)), gender=GENDER.get(g, hex(g)), kind=c["kind"],
                        name=c["name"] + (" [EMPTY]" if empty else ""), alt="; ".join(alt), bytes=c["decoded_bytes"] if c["decoded_bytes"] is not None else c["block_bytes"],
                        template=tpl, hat_partner=partner, frames=frames, variant=f"{c['variant']:#x}", vbyte2=(c["variant"] >> 16) & 0xFF))
    cols = ["index", "slot", "bits", "gender", "kind", "name", "alt", "bytes", "template", "hat_partner", "frames", "variant", "vbyte2"]
    lines = ["\t".join(cols)] + ["\t".join(str(r[k]) for k in cols) for r in out]
    (MODULE / "research" / "catalog-slots.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    md = ["# Avatar Asset Package items by slot", "",
          "Generated by tools/catalog_slots.py from the pinned TOC (research/catalog.tsv has the raw view). Gender = TOC variant top byte.",
          "Garments show their hiding-template index; hair shows the index of the hat-less partner of a \"(Hat)\" variant;",
          "textures show their frame count (spans: eyes/mouth expression frames).", ""]
    order = list(SLOTS.values())
    for slot in order:
        items = [r for r in out if r["slot"] == slot]
        if not items:
            continue
        kinds = sorted({r["kind"] for r in items})
        g = {k: sum(1 for r in items if r["gender"] == k) for k in ("male", "female", "both")}
        md.append(f"## {slot} ({len(items)}: {', '.join(kinds)}; male {g['male']}, female {g['female']}, both {g['both']})")
        md.append("")
        md.append("| index | gender | name | bits | template | hat partner | frames |")
        md.append("|---|---|---|---|---|---|---|")
        for r in items:
            md.append(f"| {r['index']} | {r['gender']} | {r['name']}{' (' + r['alt'] + ')' if r['alt'] else ''} | {r['bits']} | {r['template']} | {r['hat_partner']} | {r['frames']} |")
        md.append("")
    (MODULE / "research" / "catalog-slots.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    for slot in order:
        n = sum(1 for r in out if r["slot"] == slot)
        if n:
            print(f"{slot:16} {n}")
    print("rows", len(out), "hair (Hat) without partner:", [r["index"] for r in out if r["hat_partner"] == "NONE"],
          "template errors:", [r["index"] for r in out if str(r["template"]).startswith("ERR")],
          "texture errors:", [r["index"] for r in out if str(r["frames"]).startswith("ERR")])


if __name__ == "__main__":
    main()
